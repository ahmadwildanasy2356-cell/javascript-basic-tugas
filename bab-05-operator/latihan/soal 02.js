
// Soal 1 — Operator Modulus (%)
const angka = 29;

// Menghitung sisa hasil pembagian
const mod2 = angka % 2;
const mod4 = angka % 4;
const mod5 = angka % 5;

// Menampilkan Hasil Output
console.log(`${angka} % 2 = ${mod2}`);
console.log(`${angka} % 4 = ${mod4}`);
console.log(`${angka} % 5 = ${mod5}`);