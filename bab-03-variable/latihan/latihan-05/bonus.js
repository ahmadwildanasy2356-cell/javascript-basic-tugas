// Menggunakan const untuk nilai yang tidak berubah (dengan camelCase)
const nama = "Budi";
const kota = "Bandung";

// Menggunakan let untuk nilai yang akan diubah di kemudian hari
let umur = 20;

// Mengubah nilai umur
