// Menggunakan 'let' karena nilai saldo akan diubah/ditambahkan
let saldo = 100000;

// Menampilkan saldo awal
console.log("Saldo Awal :", saldo);

// Menambahkan saldo sebesar 50000
saldo = saldo + 50000; // Bisa juga ditulis: saldo += 50000;

// Menampilkan saldo akhir
console.log("\nSaldo Akhir :", saldo);