let umur = 18;

if (umur >= 60) {
  console.log("Kategori : Lansia");
} 
else if (umur >= 18) {
  console.log("Kategori : Dewasa");
}
 else if (umur >= 13) {
  console.log("Kategori : Remaja");
}
 else if (umur >= 6) {
  console.log("Kategori : Anak-anak");
}
 else if (umur >= 0) {
  console.log("Kategori : Balita");
}
 else {
  console.log("Umur tidak valid");
}